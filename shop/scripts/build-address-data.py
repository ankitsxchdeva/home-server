#!/usr/bin/env python3
"""Build shop/site/address-data.json and shop/apps-script/AddressData.gs.

Source: Google's address metadata (libaddressinput), as bundled in the
BSD-licensed `google-i18n-address` package (pip download google-i18n-address).

Usage: python3 -I build-address-data.py path/to/i18naddress/data/all.json
"""
import json, os, sys

src = json.load(open(sys.argv[1], encoding="utf-8"))
here = os.path.dirname(os.path.abspath(__file__))
KEEP = ["fmt", "require", "upper", "zip", "zipex", "zip_name_type",
        "state_name_type", "locality_name_type", "sublocality_name_type"]

countries = {}
for key, d in src.items():
    if "/" in key or key == "ZZ" or len(key) != 2:
        continue
    c = {k: d[k] for k in KEEP if k in d}
    c["name"] = d.get("name", key)
    subs = d.get("sub_keys")
    if subs:
        keys = subs.split("~")
        # Prefer latin names where the country publishes them (e.g. JP, CN)
        names = (d.get("sub_lnames") or d.get("sub_names") or subs).split("~")
        lkeys = (d.get("sub_lnames") and d.get("sub_keys")) and keys
        regions = []
        for i, k in enumerate(keys):
            child = src.get(f"{key}/{k}", {})
            r = {"k": k, "n": names[i] if i < len(names) else k}
            if child.get("zip"):
                r["z"] = child["zip"]
            regions.append(r)
        c["regions"] = regions
    countries[key] = c

out = os.path.join(here, "..", "site", "address-data.json")
with open(out, "w", encoding="utf-8") as f:
    json.dump(countries, f, ensure_ascii=False, separators=(",", ":"))

# Server copy: only what the server re-checks (required fields, postal formats).
server = {}
for key, c in countries.items():
    s = {"r": c.get("require", "AC")}
    if c.get("zip"):
        s["z"] = c["zip"]
    if c.get("regions"):
        s["s"] = {r["k"]: r.get("z", "") for r in c["regions"]}
        s["sn"] = {r["n"]: r["k"] for r in c["regions"] if r["n"] != r["k"]}
    server[key] = s
gs = os.path.join(here, "..", "apps-script", "AddressData.gs")
with open(gs, "w", encoding="utf-8") as f:
    f.write("// Generated by shop/scripts/build-address-data.py. Do not edit by hand.\n")
    f.write("// Source: Google address metadata (libaddressinput) via google-i18n-address (BSD-3).\n")
    f.write("var ADDRESS_DATA = " + json.dumps(server, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(countries), "countries;", os.path.getsize(out), "bytes site;", os.path.getsize(gs), "bytes server")
